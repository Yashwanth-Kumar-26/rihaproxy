from rihaproxy.backends.hub import BackendHub, get_hub
from rihaproxy.config import settings
from rihaproxy.storage.db import get_storage

logger = logging.getLogger(__name__)


class GatewayRouter:
    """
    Routes incoming requests to appropriate backends.
    Handles model resolution, combo detection, and aliasing.
    """

    def __init__(self, hub: BackendHub | None = None):
        self.hub = hub or get_hub()
        self.storage = get_storage()
        self._config_aliases: dict[str, str] = {}
        self._load_config_json()

    def _load_config_json(self) -> None:
        """Load aliases from config.json generated by setup.sh if it exists."""
        import json
        config_path = Path(__file__).parent.parent.parent.parent / "config.json"
        if config_path.exists():
            try:
                with open(config_path) as f:
                    config = json.load(f)
                
                # Map Anthropic tiers to the selected models
                mappings = {
                    "claude-3-opus-20240229": config.get("model_opus"),
                    "claude-3-sonnet-20240229": config.get("model_sonnet"),
                    "claude-3-5-sonnet-20240620": config.get("model_sonnet"),
                    "claude-3-5-sonnet-20241022": config.get("model_sonnet"),
                    "claude-3-haiku-20240307": config.get("model_haiku"),
                    "claude-3-5-haiku-20241022": config.get("model_haiku"),
                    "default": config.get("model_default")
                }
                
                for source, target in mappings.items():
                    if target and target not in ("[SAME_AS_DEFAULT]", "[CUSTOM_MODEL]"):
                        self._config_aliases[source] = target
                        
                # Update default backend provider if specified
                if "provider" in config:
                    from rihaproxy.config import settings
                    settings.default_backend = config["provider"]
            except Exception as e:
                logger.warning("failed_to_load_config_json", error=str(e))

    def resolve_model(self, model: str) -> str:
        """
        Resolve a model string to its actual target.

        Resolution order:
        1. Check model combos
        2. Check model aliases (exact match)
        3. Check tier keywords (opus, sonnet, haiku)
        4. Check config.json aliases (exact match)
        5. Return as-is
        """
        # 1. Check for combo
        combo = self.storage.get_combo(model)
        if combo:
            models = combo.get("models", [])
            if models:
                return models[0]

        # 2. Check aliases (exact match)
        resolved = self.storage.resolve_alias(model)
        if resolved != model:
            logger.debug("alias_resolved from=%s to=%s", model, resolved)
            return resolved

        # 3. Tier aliases (Anthropic style keywords)
        model_lower = model.lower()
        import json
        config_path = Path(__file__).parent.parent.parent.parent / "config.json"
        
        # We'll use the config directly for tiers to ensure it matches claudefree behavior
        if config_path.exists():
            try:
                with open(config_path) as f:
                    config = json.load(f)
                
                target = None
                if "opus" in model_lower:
                    target = config.get("model_opus")
                elif "sonnet" in model_lower:
                    target = config.get("model_sonnet")
                elif "haiku" in model_lower:
                    target = config.get("model_haiku")
                
                if target and target not in ("[SAME_AS_DEFAULT]", "[CUSTOM_MODEL]"):
                    logger.debug("tier_resolved from=%s to=%s", model, target)
                    return target
                
                # If tier not found or is default, return default model
                if any(tier in model_lower for tier in ["opus", "sonnet", "haiku"]):
                    return config.get("model_default", model)
            except Exception:
                pass

        # 4. Check config.json aliases (exact match)
        if model in self._config_aliases:
            resolved = self._config_aliases[model]
            logger.debug("config_alias_resolved from=%s to=%s", model, resolved)
            return resolved

        return model

    def get_combo_models(self, combo_name: str) -> list[str]:
        """Get the model chain for a combo."""
        combo = self.storage.get_combo(combo_name)
        if combo:
            return combo.get("models", [])
        return [combo_name]

    async def route_chat(
        self,
        model: str,
        messages: list[dict[str, Any]],
        stream: bool = False,
        **kwargs: Any,
    ) -> Any:
        """
        Route a chat request through the gateway.

        Handles:
        - Model resolution (aliases, combos)
        - Backend selection
        - Fallback chain on failure
        """
        resolved_model = self.resolve_model(model)

        logger.info(
            "routing_request original=%s resolved=%s provider=%s stream=%s",
            model, resolved_model, self.hub.resolve_provider(resolved_model), stream,
        )

        return await self.hub.chat(
            model=resolved_model,
            messages=messages,
            stream=stream,
            **kwargs,
        )

    async def route_with_fallback(
        self,
        models: list[str],
        messages: list[dict[str, Any]],
        stream: bool = False,
        **kwargs: Any,
    ) -> Any:
        """
        Route a request trying each model in sequence until one succeeds.
        Used for combo fallback chains.
        """
        errors: list[str] = []

        for model in models:
            resolved = self.resolve_model(model)
            try:
                result = await self.hub.chat(
                    model=resolved,
                    messages=messages,
                    stream=stream,
                    **kwargs,
                )
                logger.info("fallback_success model=%s", resolved)
                return result
            except Exception as e:
                errors.append(f"{resolved}: {e}")
                logger.warning("fallback_failed model=%s error=%s", resolved, str(e))
                continue

        # All models failed
        from rihaproxy.backends.base import BackendError
        raise BackendError(f"All models failed: {'; '.join(errors)}")

